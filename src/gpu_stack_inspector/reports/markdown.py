"""Markdown output: an issue-ready dossier of an already redacted snapshot.

Collected text is escaped so a path containing ``|`` cannot break a table and ``<tag>``
cannot become HTML in an issue tracker; values go in code spans whose fence is longer
than any backtick run they contain.
"""

from __future__ import annotations

import re
from collections import Counter

from gpu_stack_inspector.models import Finding, InterpreterFacts, Snapshot, Status
from gpu_stack_inspector.reports.terminal import redaction_line, runtime_summary
from gpu_stack_inspector.rules.comparison import torch_build_label

_SPECIAL = re.compile(r"([\\`*_\[\]<>|#])")
_PROBLEMS = (Status.FAIL, Status.WARN, Status.UNKNOWN)
_LABEL = {
    Status.FAIL: "FAIL",
    Status.WARN: "WARN",
    Status.UNKNOWN: "UNKNOWN",
    Status.PASS: "PASS",
    Status.NOT_APPLICABLE: "N/A",
    Status.NOT_TESTED: "NOT TESTED",
}


def text(value: str) -> str:
    """Plain text that Markdown and HTML will not interpret; one line."""
    return _SPECIAL.sub(r"\\\1", " ".join(value.split()))


def code(value: str) -> str:
    """An inline code span that survives any backticks inside the value."""
    flat = " ".join(value.split())
    longest = max((len(run) for run in re.findall(r"`+", flat)), default=0)
    fence = "`" * (longest + 1)
    padding = " " if flat.startswith("`") or flat.endswith("`") else ""
    return f"{fence}{padding}{flat}{padding}{fence}"


def _cell(value: str | None, *, as_code: bool = False) -> str:
    if value is None:
        return "—"
    return code(value) if as_code else text(value)


def render_markdown(snapshot: Snapshot) -> str:
    lines: list[str] = ["# GPU Stack Inspector report", ""]
    lines.append(
        f"Generated by gpu-stack-inspector {text(snapshot.tool_version)} on "
        f"{text(snapshot.created_at)}. Read-only: nothing was installed or changed."
    )
    redacted = redaction_line(snapshot)
    if redacted:
        lines.append(f"{text(redacted)}.")
    lines += ["", *_summary(snapshot), "", *_system(snapshot)]
    if snapshot.interpreters:
        lines += ["", *_environments(snapshot.interpreters)]
    if snapshot.comparison:
        lines += ["", *_differences(snapshot)]
    if snapshot.findings:
        lines += ["", *_findings(snapshot)]
    if snapshot.probe_failures:
        lines += ["", "## Not checked", ""]
        lines += [f"- {text(f.probe)}: {text(f.detail)}" for f in snapshot.probe_failures]
    return "\n".join(lines) + "\n"


def _summary(snapshot: Snapshot) -> list[str]:
    lines = ["## Summary", ""]
    problems = [f for f in snapshot.findings if f.status in _PROBLEMS and not f.caused_by]
    order = {status: i for i, status in enumerate(_PROBLEMS)}
    for finding in sorted(problems, key=lambda f: order[f.status]):
        where = "" if finding.subject == "host" else f" ({text(finding.subject)})"
        lines.append(
            f"- **{_LABEL[finding.status]}** {code(finding.id)}{where}: {text(finding.summary)}"
        )
    if not problems:
        lines.append("No problems found." if snapshot.findings else "No checks were run.")
    counts = Counter(f.status for f in snapshot.findings)
    if snapshot.findings:
        lines += [
            "",
            f"{counts[Status.FAIL]} failed, {counts[Status.WARN]} warnings, "
            f"{counts[Status.UNKNOWN]} unknown, {counts[Status.PASS]} passed.",
        ]
    return lines


def _system(snapshot: Snapshot) -> list[str]:
    rows: list[tuple[str, str]] = []
    host = snapshot.host
    if host is not None:
        system = " · ".join(p for p in (f"{host.system} {host.machine}", host.distribution) if p)
        rows.append(("OS", text(system)))
        rows.append(("Kernel", _cell(host.kernel)))
    nvidia = snapshot.nvidia
    if nvidia is not None:
        if nvidia.smi_path is None:
            rows.append(("NVIDIA driver", "nvidia-smi not found"))
        else:
            driver = _cell(nvidia.driver_version)
            cuda = _cell(nvidia.max_cuda_version)
            rows.append(("NVIDIA driver", f"{driver} (supports CUDA up to {cuda})"))
        for gpu in nvidia.gpus:
            memory = f"{gpu.memory_total_mib} MiB" if gpu.memory_total_mib is not None else "? MiB"
            details = f"{text(gpu.name)}, {memory}, compute {_cell(gpu.compute_capability)}"
            rows.append((f"GPU {gpu.index}", details))
    toolkit = snapshot.toolkit
    if toolkit is not None:
        rows.append(("nvcc", _cell(toolkit.nvcc_version) if toolkit.nvcc_path else "not installed"))
        for found in toolkit.toolkits:
            rows.append(("CUDA toolkit", f"{code(found.path)} ({_cell(found.version)})"))
    for variable in snapshot.cuda_environment:
        rows.append((text(variable.name), code(variable.value) if variable.value else '`""`'))
    if not rows:
        return ["## System", "", "Not inspected."]
    return ["## System", "", "| | |", "| --- | --- |", *(f"| {k} | {v} |" for k, v in rows)]


def _environments(interpreters: tuple[InterpreterFacts, ...]) -> list[str]:
    lines = [
        "## Environments",
        "",
        "| | Path | Python | Kind | torch | Build | Runtime |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for i in interpreters:
        kind = ", ".join(k for k, on in (("conda", i.conda), ("venv", i.virtualenv)) if on) or "—"
        torch = i.torch.version if i.torch else None
        runtime = runtime_summary(i) or "not tested"
        lines.append(
            f"| {text(i.label)} | {code(i.path)} | {_cell(i.version)} | {kind} "
            f"| {_cell(torch)} | {_cell(torch_build_label(i))} | {text(runtime)} |"
        )
    return lines


def _differences(snapshot: Snapshot) -> list[str]:
    rows = [row for row in snapshot.comparison if row.differs]
    labels = [text(i.label) for i in snapshot.interpreters]
    lines = ["## Differences", ""]
    if not rows:
        return [*lines, "No differences in the compared fields."]
    lines.append("| Field | " + " | ".join(labels) + " |")
    lines.append("| --- |" + " --- |" * len(labels))
    for row in rows:
        values = " | ".join(_cell(value) for value in row.values)
        lines.append(f"| {text(row.field)} | {values} |")
    return lines


def _findings(snapshot: Snapshot) -> list[str]:
    paths = {i.label: i.path for i in snapshot.interpreters}
    lines = ["## Findings"]
    for subject in ["host", *paths, "comparison"]:
        group = [f for f in snapshot.findings if f.subject == subject]
        if not group:
            continue
        heading = {"host": "Host", "comparison": "Comparison"}.get(subject)
        lines += ["", f"### {heading or f'{text(subject)} ({code(paths[subject])})'}", ""]
        for finding in group:
            lines += _finding(finding)
    return lines


def _finding(finding: Finding) -> list[str]:
    summary = text(finding.summary)
    if finding.caused_by:
        summary += f" (follows from {code(finding.caused_by)})"
    lines = [f"- **{_LABEL[finding.status]}** {code(finding.id)} {summary}"]
    if finding.status not in _PROBLEMS:
        return lines
    lines.append(f"  - Why: {text(finding.reason)}")
    if finding.recommended_action:
        lines.append(f"  - Next: {text(finding.recommended_action)}")
    if finding.verify_command:
        lines.append(f"  - Check: {code(finding.verify_command)}")
    lines += [f"  - Note: {text(limitation)}" for limitation in finding.limitations]
    return lines
